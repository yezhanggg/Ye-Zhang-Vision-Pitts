"""Step 13: the Colab notebook that casts Pittsburgh's shadows on a GPU, or a small CPU dry run of the same code.

The shadow march (src/visionpitts/shadow.py) is a CUDA kernel, so the real run happens in Google Colab on a T4 GPU,
the way MUSA 6950 Assignment 3 ran. This script writes nopush/shadow/VisionPitts_shadow.ipynb with shadow.py and
remotezip.py embedded word for word; the notebook downloads the 2015 lidar surface from PASDA, checks the kernel
against the NumPy reference, casts every 30-minute step of June 21, September 22 and December 21, and hands back
one zip of map pages. Never edit the notebook by hand: change the code here or in shadow.py and write it again.

--dry-run N does the whole thing on this machine instead, without a GPU: the surface is reduced N times each way
(highest cell of each block) and the NumPy reference casts the shadows. Coarse, but the files have the real layout,
which is enough to build and test the map layer. Output: nopush/shadow/dryrun/.

After the Colab run: unzip the download into nopush/shadow/out/ and run scripts/14_publish_shadows.py.
Run: uv run python scripts/13_build_shadow_notebook.py [--dry-run 8]
"""
