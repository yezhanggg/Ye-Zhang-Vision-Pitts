def notebook() -> dict:
    files = {name: base64.b64encode((SRC / name).read_bytes()).decode() for name in ("shadow.py", "remotezip.py")}
    cells = [("markdown", INTRO), ("code", f"FILES = {json.dumps(files)}\n" + SETUP), ("code", GPU), ("code", SURFACE), ("code", CHECK), ("code", RUN), ("code", QA), ("code", ZIP)]
    return {
        "nbformat": 4,
        "nbformat_minor": 0,
        "metadata": {"colab": {"provenance": [], "gpuType": "T4"}, "accelerator": "GPU", "kernelspec": {"name": "python3", "display_name": "Python 3"}, "language_info": {"name": "python"}},
        "cells": [{"cell_type": kind, "metadata": {}, "source": text.splitlines(keepends=True), **({"outputs": [], "execution_count": None} if kind == "code" else {})} for kind, text in cells],
    }


def dry_run(factor: int) -> None:
    import numpy as np

    from visionpitts import shadow as sh

    folder = sh.fetch_dsm(NOPUSH / "pasda")
    dsm, x0, y0, cell = sh.read_dsm(folder)
    dsm, spikes = sh.despike(dsm)
    h, w = (dsm.shape[0] // factor) * factor, (dsm.shape[1] // factor) * factor
    small = np.ascontiguousarray(dsm[:h, :w].reshape(h // factor, factor, w // factor, factor).max(axis=(1, 3)))
    print(f"dry run: {small.shape[1]:,} x {small.shape[0]:,} cells of {cell * factor:g} ft ({spikes} spike cells removed)")
    out = NOPUSH / "dryrun"
    sh.build(small, x0, y0, cell * factor, sh.ReferenceCaster(small, cell * factor), out,
             engine=f"NumPy reference, surface reduced {factor}x (dry run)")
    print(f"wrote {out.relative_to(NOPUSH.parents[1])}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--dry-run", type=int, metavar="N", help="cast on this machine with the surface reduced N times each way")
    args = ap.parse_args()
    if args.dry_run:
        return dry_run(args.dry_run)
    NOPUSH.mkdir(parents=True, exist_ok=True)
    NOTEBOOK.write_text(json.dumps(notebook(), indent=1))
    print(f"wrote {NOTEBOOK.relative_to(NOPUSH.parents[1])} ({NOTEBOOK.stat().st_size:,} bytes)")
    print("Open it in Colab (File > Upload notebook), set the runtime to T4 GPU, Run all.")


if __name__ == "__main__":
    main()
